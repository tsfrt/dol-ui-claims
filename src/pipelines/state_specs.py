def file_columns(code):
    return ["RECORD_ID", "EVENT_TS"] + [p.lstrip("$.") for p in STATE_SPECS[code]["fields"].values()]


def share_columns(code):
    """Typed columns of a Delta Sharing state's claim status table, in table order."""
    cols = [("event_id", "STRING")]
    cols += [(path.lstrip("$."), SHARE_COLUMN_TYPES.get(field, "STRING")) for field, path in STATE_SPECS[code]["fields"].items()]
    return cols + [("status_changed_at", "TIMESTAMP")]


def share_staged_table(catalog, code):
    s = STATE_SPECS[code]["share"]
    return f"{catalog}.{s['schema']}.{s['table']}"

